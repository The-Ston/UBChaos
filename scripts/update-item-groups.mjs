// Regenerates public/item-groups.js from the game files (CommunityDragon).
// Usage: node scripts/update-item-groups.mjs [--out <file>]
// Run daily by .github/workflows/item-groups.yml, which publishes a fix release
// when the groups change.
import { appendFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { patchName } from "../public/bravery.js";
import { fetchGameItemGroups } from "./item-groups-source.mjs";

const outIndex = process.argv.indexOf("--out");
const output = outIndex > 0 ? process.argv[outIndex + 1] : fileURLToPath(new URL("../public/item-groups.js", import.meta.url));

const { groups, data } = await fetchGameItemGroups();
const lines = Object.entries(groups).map(([name, ids]) => {
  const names = ids.map((id) => data.items[id].name).join(", ");
  return `  // ${names}\n  ${JSON.stringify(name)}: ${JSON.stringify(ids).replaceAll(",", ", ")},`;
});
const source = `// Generated by scripts/update-item-groups.mjs from the game files, do not edit.
// Items in the same group cannot be owned together (legendaries the rolls draw from).
export const ITEM_GROUPS = {
${lines.join("\n")}
};
`;

const previous = existsSync(output) ? readFileSync(output, "utf8") : "";
writeFileSync(output, source);
console.log(previous === source ? "Item groups unchanged" : `Item groups written to ${output}`);
if (process.env.GITHUB_OUTPUT) appendFileSync(process.env.GITHUB_OUTPUT, `patch=${patchName(data.version)}\n`);
